  <!-- Header -->
  <div class="text-center mb-10">
    <div class="w-16 h-16 gradient-brand rounded-2xl flex items-center justify-center mx-auto mb-4 shadow-xl">
      <svg class="w-9 h-9 text-white" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M19 11H5m14 0a2 2 0 012 2v6a2 2 0 01-2 2H5a2 2 0 01-2-2v-6a2 2 0 012-2m14 0V9a2 2 0 00-2-2M5 11V9a2 2 0 012-2m0 0V5a2 2 0 012-2h6a2 2 0 012 2v2M7 7h10"/></svg>
    </div>
    <h1 class="text-3xl font-extrabold text-white">Installer NexusMC</h1>
    <p class="text-slate-400 mt-2">Opsæt dit Minecraft community-website</p>
  </div>

  <!-- Steps indicator -->
  <div class="flex items-center justify-center gap-2 mb-8">
    <?php foreach ([1 => 'Krav', 2 => 'Database', 3 => 'Admin', 4 => 'Færdig'] as $n => $label): ?>
    <div class="flex items-center gap-2">
      <div class="w-7 h-7 rounded-full flex items-center justify-center text-xs font-bold
        <?= $step > $n ? 'bg-brand text-white' : ($step === $n ? 'bg-brand text-white ring-4 ring-brand/25' : 'bg-slate-800 text-slate-500') ?>">
        <?= $step > $n ? '✓' : $n ?>
      </div>
      <span class="text-xs hidden sm:block <?= $step === $n ? 'text-white font-medium' : 'text-slate-500' ?>"><?= $label ?></span>
    </div>
    <?php if ($n < 4): ?><div class="w-8 h-px bg-slate-700"></div><?php endif; ?>
    <?php endforeach; ?>
  </div>

  <!-- Errors -->
  <?php if (!empty($errors)): ?>
  <div class="bg-red-500/10 border border-red-500/20 rounded-xl p-4 mb-5 space-y-1">
    <?php foreach ($errors as $err): ?>
    <p class="text-sm text-red-400 flex items-center gap-2">
      <span class="text-red-500">✕</span><?= htmlspecialchars($err, ENT_QUOTES | ENT_HTML5, 'UTF-8') ?>
    </p>
    <?php endforeach; ?>
  </div>
  <?php endif; ?>

  <!-- STEP 1: Requirements -->
  <?php if ($step === 1): ?>
  <div class="glass rounded-2xl p-7">
    <h2 class="text-xl font-bold text-white mb-5">Systemkrav</h2>
    <div class="space-y-3 mb-6">
      <?php foreach ($reqs as $label => $pass): ?>
      <div class="flex items-center justify-between py-2.5 border-b border-slate-800 last:border-0">
        <span class="text-sm text-slate-300"><?= htmlspecialchars($label) ?></span>
        <?php if ($pass): ?>
        <span class="text-xs bg-emerald-500/15 text-emerald-400 border border-emerald-500/25 px-2.5 py-0.5 rounded-full font-medium">✓ OK</span>
        <?php else: ?>
        <span class="text-xs bg-red-500/15 text-red-400 border border-red-500/25 px-2.5 py-0.5 rounded-full font-medium">✕ Fejl</span>
        <?php endif; ?>
      </div>
      <?php endforeach; ?>
    </div>
    <?php if (!in_array(false, $reqs, true)): ?>
    <a href="?step=2" class="block text-center py-3 bg-brand hover:bg-brand-dark text-white font-semibold rounded-xl transition-colors">
      Fortsæt →
    </a>
    <?php else: ?>
    <p class="text-sm text-red-400 text-center">Ret fejlene ovenfor og opdater siden.</p>
    <?php endif; ?>
  </div>

  <!-- STEP 2: Database -->
  <?php elseif ($step === 2): ?>
  <div class="glass rounded-2xl p-7">
    <h2 class="text-xl font-bold text-white mb-5">Databaseopsætning</h2>
    <form method="POST" action="?step=2" class="space-y-4">
      <div class="grid sm:grid-cols-2 gap-4">
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Database host</label>
          <input type="text" name="db_host" value="localhost" required
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Database navn</label>
          <input type="text" name="db_name" value="nexusmc" required
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Brugernavn</label>
          <input type="text" name="db_user" required
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Adgangskode</label>
          <input type="password" name="db_pass"
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Tabel-præfiks</label>
          <input type="text" name="db_prefix" value="nmc_"
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
        <div>
          <label class="block text-sm font-medium text-slate-300 mb-1.5">Site URL</label>
          <input type="url" name="app_url" value="http://<?= htmlspecialchars($_SERVER['HTTP_HOST']) ?>"
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
        </div>
      </div>
      <button type="submit" class="w-full py-3 bg-brand hover:bg-brand-dark text-white font-semibold rounded-xl transition-colors mt-2">
        Test forbindelse &amp; fortsæt →
      </button>
    </form>
  </div>

  <!-- STEP 3: Admin account -->
  <?php elseif ($step === 3): ?>
  <div class="glass rounded-2xl p-7">
    <h2 class="text-xl font-bold text-white mb-5">Opret administrator konto</h2>
    <form method="POST" action="?step=3" class="space-y-4">
      <div>
        <label class="block text-sm font-medium text-slate-300 mb-1.5">Site navn</label>
        <input type="text" name="site_name" value="NexusMC" required
               class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white focus:outline-none focus:border-brand transition-colors">
      </div>
