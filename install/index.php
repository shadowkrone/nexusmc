          <input type="text" name="admin_username" required placeholder="Brugernavn"
                 class="w-full bg-slate-900 border border-slate-700 rounded-lg px-4 py-2.5 text-white placeholder-slate-500 focus:outline-none focus:border-brand transition-colors">
