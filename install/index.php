<?php
ob_start();
define('INSTALL_MODE', true);
define('ROOT', dirname(__DIR__));

ini_set('session.cookie_httponly', '1');
session_start();

$step   = (int)($_GET['step'] ?? 1);
$errors = [];

// ---- Requirements check ----
$reqs = [
    'PHP 8.1+'        => version_compare(PHP_VERSION, '8.1', '>='),
    'PDO MySQL'       => extension_loaded('pdo_mysql'),
    'OpenSSL'         => extension_loaded('openssl'),
    'JSON'            => extension_loaded('json'),
    'Config writable' => is_writable(ROOT . '/config') || (mkdir(ROOT . '/config', 0755, true) && is_writable(ROOT . '/config')),
];

// ---- Step 2: DB connection test ----
if ($step === 2 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $_SESSION['db'] = [
        'host'   => trim($_POST['db_host'] ?? 'localhost'),
        'name'   => trim($_POST['db_name'] ?? ''),
        'user'   => trim($_POST['db_user'] ?? ''),
        'pass'   => $_POST['db_pass'] ?? '',
        'prefix' => preg_replace('/[^a-z0-9_]/i', '', trim($_POST['db_prefix'] ?? 'nmc_')),
    ];
    $_SESSION['app_url'] = rtrim(trim($_POST['app_url'] ?? ''), '/');

    try {
        $pdo = new PDO(
            "mysql:host={$_SESSION['db']['host']};charset=utf8mb4",
            $_SESSION['db']['user'],
            $_SESSION['db']['pass'],
            [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
        );
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$_SESSION['db']['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        header('Location: ?step=3');
        exit;
    } catch (PDOException $e) {
        $errors[] = 'Database fejl: ' . $e->getMessage();
    }
}

// ---- Step 3: Admin account + finalize ----
if ($step === 3 && $_SERVER['REQUEST_METHOD'] === 'POST') {
    $adminUser  = trim($_POST['admin_username'] ?? '');
    $adminEmail = trim($_POST['admin_email'] ?? '');
    $adminPass  = $_POST['admin_password'] ?? '';
    $siteName   = trim($_POST['site_name'] ?? 'NexusMC');

    if (!$adminUser || !$adminEmail || !$adminPass) {
        $errors[] = 'Udfyld alle felter.';
    }
    if (strlen($adminPass) < 8) {
        $errors[] = 'Adgangskode skal mindst være 8 tegn.';
    }

    if (empty($errors)) {
        try {
            $db  = $_SESSION['db'];
            $pdo = new PDO(
                "mysql:host={$db['host']};dbname={$db['name']};charset=utf8mb4",
                $db['user'],
                $db['pass'],
                [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]
            );

            // Run schema
            $sql = file_get_contents(ROOT . '/database/schema.sql');
            $sql = str_replace('{PREFIX}', $db['prefix'], $sql);
            // Split on semicolons, skip comments and empty lines
            foreach (explode(';', $sql) as $query) {
                $query = trim($query);
                if ($query && !str_starts_with($query, '--')) {
                    $pdo->exec($query);
                }
            }

            // Create admin user
            $pdo->prepare(
                "INSERT INTO `{$db['prefix']}users` (username, email, password, role, created_at, last_seen)
                 VALUES (?, ?, ?, 'admin', NOW(), NOW())"
            )->execute([$adminUser, strtolower($adminEmail), password_hash($adminPass, PASSWORD_BCRYPT)]);

            // Update site name setting
            $pdo->prepare(
                "UPDATE `{$db['prefix']}settings` SET value = ? WHERE `key` = 'site_name'"
            )->execute([$siteName]);

            // Write config file
            $secret = bin2hex(random_bytes(32));
            $config  = "<?php\n";
            $config .= "// NexusMC Configuration — generated by installer\n";
            $config .= "define('DB_HOST',    " . var_export($db['host'],   true) . ");\n";
            $config .= "define('DB_NAME',    " . var_export($db['name'],   true) . ");\n";
            $config .= "define('DB_USER',    " . var_export($db['user'],   true) . ");\n";
            $config .= "define('DB_PASS',    " . var_export($db['pass'],   true) . ");\n";
            $config .= "define('DB_CHARSET', 'utf8mb4');\n";
            $config .= "define('DB_PREFIX',  " . var_export($db['prefix'], true) . ");\n\n";
            $config .= "define('APP_URL',    " . var_export($_SESSION['app_url'] ?? '', true) . ");\n";
            $config .= "define('APP_SECRET', " . var_export($secret, true) . ");\n";
            $config .= "define('THEME',      'default');\n";
            $config .= "define('TIMEZONE',   'Europe/Copenhagen');\n\n";
            $config .= "date_default_timezone_set(TIMEZONE);\n";

            file_put_contents(ROOT . '/config/config.php', $config);

            header('Location: ?step=4');
            exit;
        } catch (Throwable $e) {
            $errors[] = 'Fejl: ' . $e->getMessage();
        }
    }
}
